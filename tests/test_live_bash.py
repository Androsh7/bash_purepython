def run_real_bash(script: str, cwd: Path) -> tuple[str, int]:
    """Return what the real bash prints and exits with for a script

    Args:
        script: The script text
        cwd: An empty directory to run in

    Returns:
        Standard output and the exit code
    """
    completed = subprocess.run(
        [BASH_PATH or "bash", "-c", script],
        cwd=cwd,
        env={**BASH_ENVIRONMENT, "SYSTEMROOT": os.environ.get("SYSTEMROOT", "")},
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=BASH_TIMEOUT_S,
    )
    return completed.stdout, completed.returncode


