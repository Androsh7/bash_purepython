@pytest.mark.parametrize("script", SCRIPTS, ids=[f"script_{index}" for index in range(len(SCRIPTS))])
def test_engine_matches_real_bash(script: str, tmp_path: Path) -> None:
    """Check that the engine prints the same standard output and exit code as bash for one script"""
    bash_directory = tmp_path / "bash"
    engine_directory = tmp_path / "engine"
    bash_directory.mkdir()
    engine_directory.mkdir()
    shell = build_harness(engine_directory)
    shell.state.variables["HOME"] = BASH_ENVIRONMENT["HOME"]

    expected_stdout, expected_exit_code = run_real_bash(script, bash_directory)
